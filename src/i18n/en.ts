// English: the source language. Every other locale must provide the same
// shape (`Messages`), so a missing or extra string is a type error.
//
// Names passed to prompt templates are in "running text" form: for French,
// Spanish and Italian the place dictionaries include the definite article
// ("le Nil", "el Nilo"), and `bare()` strips it where a name stands alone
// as an answer option.

export interface Unit {
  /** Singular with its indefinite article where the language has one: "a state", "une région". */
  one: string;
  many: string;
  /** Interrogative agreeing with the unit, for languages that need it ("Cuántas", "Quante"). */
  howMany?: string;
}

