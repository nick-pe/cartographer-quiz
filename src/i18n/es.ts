// Rivers, seas and mountains carry their article in the place dictionary
// ("el Nilo"). Templates avoid "de"/"a" right before such a name, where
// Spanish would contract it ("del", "al").

const bare = (name: string) => {
  const stripped = name.replace(/^(el |la |los |las )/, "");
  return stripped.charAt(0).toUpperCase() + stripped.slice(1);
};

