// Italian fuses prepositions with articles (di + il = del), so templates
// never put a preposition right before a dictionary name that carries its
// article ("il Nilo"); they lead with the name or place it after a verb.
// Country names from the browser have no article, so they follow a colon.

const bare = (name: string) => {
  const stripped = name.replace(/^(il |lo |la |i |gli |le |l’|l')/, "");
  return stripped.charAt(0).toUpperCase() + stripped.slice(1);
};
const cap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

