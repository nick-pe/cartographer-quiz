// Country names come from the browser without an article ("France"), so
// questions about them use a colon ("France : quelle est sa capitale ?")
// rather than "de la France". Rivers, seas and mountains carry their article
// in the place dictionary ("le Nil"), which reads naturally in a sentence.

const bare = (name: string) => {
  const stripped = name.replace(/^(le |la |les |l’|l')/, "");
  return stripped.charAt(0).toUpperCase() + stripped.slice(1);
};

