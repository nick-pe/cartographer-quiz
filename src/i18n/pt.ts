// Brazilian Portuguese. Country names come from the browser without an
// article ("França"), so questions about them use a colon ("França: qual é a
// capital?") rather than "da França". Rivers, seas and mountains carry their
// article in the place dictionary ("o Nilo"); templates avoid "de"/"por"/"em"
// right before such a name, where Portuguese would contract it ("do", "pelo").

const bare = (name: string) => {
  const stripped = name.replace(/^(o |a |os |as )/, "");
  return stripped.charAt(0).toUpperCase() + stripped.slice(1);
};

/** Capitalizes a name that opens a sentence ("o Nilo" → "O Nilo"). */
const cap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

