// Korean particles depend on whether the preceding word ends in a consonant
// (받침): 은/는, 이/가, 을/를. Names come from data, so the particle is chosen
// at runtime. Non-Hangul endings (Latin regional names) are treated by their
// last letter's sound as best we can: a final vowel letter takes the vowel form.

function hasBatchim(word: string): boolean {
  const last = word.trim().replace(/[)\]」』"'”’]+$/, "").slice(-1);
  const code = last.charCodeAt(0);
  if (code >= 0xac00 && code <= 0xd7a3) return (code - 0xac00) % 28 !== 0;
  if (/[0-9]/.test(last)) return /[013678]/.test(last);
  return !/[aeiouyAEIOUY]/.test(last);
}
const josa = (word: string, withBatchim: string, without: string) => word + (hasBatchim(word) ? withBatchim : without);
const eun = (w: string) => josa(w, "은", "는");
const eul = (w: string) => josa(w, "을", "를");
const iga = (w: string) => josa(w, "이", "가");

