// Regenerates src/data/countries.ts from the world-countries package.
// Run with: npm run data
// Country data © Mohammed Le Doze, ODbL 1.0 (https://github.com/mledoze/countries).
import { writeFileSync } from "node:fs";
import countries from "world-countries";

// UN members plus the Holy See. Contested states are left out so every
// question has one defensible answer.
const EXTRA = ["VA"];

// Explorer: places nearly everyone has heard of.
const TIER1 = `US CA MX BR AR CL PE CO GB FR DE IT ES PT NL BE CH AT IE GR SE NO DK FI
PL RU UA TR EG ZA NG KE MA CN JP KR IN PK ID TH VN PH AU NZ SA IR IQ CU JM IS HU CZ`.split(/\s+/);
// Navigator adds these.
const TIER2 = `VE EC BO UY PY CR PA GT HN SV NI DO HT BS TT RO BG RS HR SI SK BA AL MK ME
EE LV LT BY MD LU MC MT CY VA LI SM AD GE AM AZ KZ UZ AF BD LK NP MM KH LA MY SG MN KP
AE QA KW JO LB SY YE OM BH DZ TN LY SD ET GH SN CI CM TZ UG RW ZW ZM AO MZ MG NA BW FJ PG
IL`.split(/\s+/);

// Where the dataset's choice differs from the most widely taught answer,
// or lists several capitals.
const CAPITAL = {
  ZA: "Pretoria", // executive capital (also Cape Town, Bloemfontein)
  SZ: "Mbabane", // administrative capital (royal/legislative: Lobamba)
  MN: "Ulaanbaatar",
  LK: "Sri Jayawardenepura Kotte", // official capital; Colombo is commercial
  AG: "St. John's",
};
// Capital questions are skipped for these (internationally disputed).
const NO_CAPITAL_QUESTIONS = new Set(["IL"]);

const NAME = {
  CI: "Côte d'Ivoire",
  CD: "DR Congo",
  CG: "Republic of the Congo",
};

const rows = countries
  .filter((c) => c.unMember || EXTRA.includes(c.cca2))
  .map((c) => {
    const name = NAME[c.cca2] ?? c.name.common;
    const capital = CAPITAL[c.cca2] ?? c.capital[0];
    const n = name.toLowerCase();
    const k = capital.toLowerCase();
    const trivial = n.includes(k) || k.includes(n);
    return {
      code: c.cca2,
      name,
      capital,
      region: c.region,
      subregion: c.subregion,
      tier: TIER1.includes(c.cca2) ? 1 : TIER2.includes(c.cca2) ? 2 : 3,
      capitalQuestions: !trivial && !NO_CAPITAL_QUESTIONS.has(c.cca2),
    };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

for (const code of [...TIER1, ...TIER2]) {
  if (!rows.some((r) => r.code === code)) throw new Error(`unknown code ${code}`);
}

const out = `// Generated by scripts/build-countries.mjs — do not edit by hand.
// Country data © Mohammed Le Doze, ODbL 1.0 (https://github.com/mledoze/countries).
import type { Country } from "./types";

export const COUNTRIES: Country[] = ${JSON.stringify(rows, null, 2)};
`;
writeFileSync(new URL("../src/data/countries.ts", import.meta.url), out);
console.log(`${rows.length} countries; tiers`, [1, 2, 3].map((t) => rows.filter((r) => r.tier === t).length));
